def t1_ham_classification(rep: Report) -> None:
    rows, src = [], []
    for run, label, role in HAM_RUNS:
        summ, met = RUNS_DIR / run / "train_summary.json", RUNS_DIR / run / "eval" / "metrics.json"
        s, m = read_json(summ), read_json(met)
        if s is None or m is None:
            rows.append({"Role": role, "Model": label, "Run": run, "Epoch": "not run"})
            continue
        src += [rel(summ), rel(met)]
        t = m["test"]
        rows.append({
            "Role": role, "Model": label, "Run": run, "Epoch": m["checkpoint_epoch"],
            "Val macro-F1": f(s["best_val_score"]),
            "Test macro-F1 [95% CI]": f"{f(t['macro_f1'])} {ci_txt(m['test_ci95']['macro_f1'])}",
            "Bal. acc": f(t["balanced_accuracy"]), "Accuracy": f(t["accuracy"]), "AUC (OvR macro)": f(t["auc"]),
            "MCC": f(t["mcc"]), "Kappa": f(t["kappa"]),
            "Mel. sensitivity": f(t["per_class"]["mel"]["sensitivity"], 3),
        })
    rep.add("t1_ham10000_classification", "T1. HAM10000 classification (test n = 1,503; val = best epoch)",
            pd.DataFrame(rows), src,
            ["Hair-removed runs are evaluated on their own (DullRazor) test images.",
             "95% CI: percentile bootstrap, 1,000 resamples (`evaluate.py`)."])


def paired_row(cmp: dict, metric: str) -> dict:
    return cmp["metrics"][metric]


def t2_ham_paired(rep: Report) -> None:
    loaded = {stem: read_json(CMP_DIR / f"{stem}.json") for stem, _, _ in HAM_PAIRED}
    family = {stem: loaded[stem]["metrics"]["macro_f1"]["p_two_sided"]
              for stem, _, fam in HAM_PAIRED if fam == "pre-specified" and loaded[stem] is not None}
    adj = holm(family)
    rows, src, notes = [], [], []
    for stem, label, fam in HAM_PAIRED:
        cmp = loaded[stem]
        if cmp is None:
            rows.append({"B − A": label, "Macro-F1 B − A [95% CI]": "not run"})
            continue
        src.append(rel(CMP_DIR / f"{stem}.json"))
        mf = paired_row(cmp, "macro_f1")
        row = {"B − A": label, "A": f(mf["a"]), "B": f(mf["b"]),
               "Macro-F1 B − A [95% CI]": f"{signed(mf['diff'])} {ci_txt(mf['diff_ci'])}",
               "p": p_txt(mf["p_two_sided"]),
               "p Holm (2 pre-specified)": p_txt(adj[stem], 2 * MIN_P) if stem in adj else "—"}
        for metric, name in [("balanced_accuracy", "Bal. acc"), ("auc", "AUC"), ("sensitivity_mel", "Mel. sens.")]:
            r = paired_row(cmp, metric)
            row[f"{name} B − A (p)"] = f"{signed(r['diff'])} ({p_txt(r['p_two_sided'])})"
        if fam is None:
            low = mf["diff_ci"]["low"]
            row["Not worse (CI low > −0.01)"] = "yes" if low > NOT_WORSE_MARGIN else "no"
            notes.append(f"{label}: lower CI bound {signed(low)} vs margin {signed(NOT_WORSE_MARGIN, 2)}.")
        rows.append(row)
    rep.add("t2_ham10000_paired", "T2. HAM10000 paired classification tests (test, 1,000 paired resamples)",
            pd.DataFrame(rows), src,
            ["Primary endpoint: macro-F1, Holm over the two pre-specified comparisons (recomputed here). "
             "Other columns are exploratory and uncorrected."] + notes)


def t3_isic(rep: Report) -> None:
    rows, src = [], []
    for run, label in ISIC_RUNS:
        met, summ = RUNS_DIR / run / "eval" / "metrics.json", RUNS_DIR / run / "train_summary.json"
        m, s = read_json(met), read_json(summ)
        if m is None:
            rows.append({"Model": label, "Run": run, "Epoch": "not run"})
            continue
        src += [rel(met)] + ([rel(summ)] if s else [])
        t, ci, cut = m["test"], m["test_ci95"], m["test_at_val_thresholds"]
        row = {"Model": label, "Run": run, "Epoch": m["checkpoint_epoch"],
               "Val AUC": f(s["best_val_score"]) if s else "—",
               "Test AUC [95% CI]": f"{f(t['auc'], 3)} {ci_txt(ci['auc'], 3)}",
               "AP [95% CI]": f"{f(t['average_precision'], 3)} {ci_txt(ci['average_precision'], 3)}",
               "Argmax sens / spec": f"{f(t['sensitivity'], 3)} / {f(t['specificity'], 3)}"}
        for name, key in [("Youden", "youden"), ("Sens ≥ 0.80", "sensitivity_0.80")]:
            c = cut[key]
            row[f"{name} cutoff"] = f(c["threshold"])
            row[f"{name} sens / spec"] = f"{f(c['metrics']['sensitivity'], 3)} / {f(c['metrics']['specificity'], 3)}"
        rows.append(row)
    rep.add("t3_isic2020_test", "T3a. ISIC 2020 test (n = 4,967, 89 melanoma; cutoffs fixed on val)",
            pd.DataFrame(rows), src,
            ["Val AUC: best epoch in `train_summary.json` (Kaggle). The local `eval_val/` rerun of the hybrid gives "
             "0.9119 vs 0.9118 here (docs/report_notes.md, ISIC 2020 hybrid).",
             "Sensitivity / specificity as computed by `evaluate.py` (float32 comparison). `compare_paired.py` "
             "counts test images tied with a cutoff as melanoma: ConvNeXt-T sens ≥ 0.80 specificity 0.8255 there "
             "vs 0.8264 here (4 images); EfficientNetV2-S 0.7181 vs 0.7187 (Youden) and 0.7946 vs 0.7952 "
             "(sens ≥ 0.80; 3 images each) (docs/report_notes.md, ISIC 2020)."])
    metrics = [("auc", "AUC"), ("average_precision", "Average precision"),
               ("sensitivity_0.80_specificity", "Specificity at sens ≥ 0.80 cutoff"),
               ("sensitivity_0.80_sensitivity", "Sensitivity at sens ≥ 0.80 cutoff"),
               ("youden_specificity", "Specificity at Youden"), ("youden_sensitivity", "Sensitivity at Youden"),
               ("argmax_specificity", "Specificity at argmax"), ("argmax_sensitivity", "Sensitivity at argmax")]
    for key, stem, a_label in (("t3b_isic2020_paired", ISIC_PAIRED, "ConvNeXt-T"),
                               ("t3c_isic2020_paired_local", ISIC_PAIRED_LOCAL, "EfficientNetV2-S")):
        cmp = read_json(CMP_DIR / f"{stem}.json")
        if cmp is None:
            continue
        rows = []
        for metric, name in metrics:
            r = cmp["metrics"][metric]
            rows.append({f"B − A (hybrid − {a_label})": name, "A": f(r["a"], 4), "B": f(r["b"], 4),
                         "Diff [95% CI]": f"{signed(r['diff'], 3)} {ci_txt(r['diff_ci'], 3)}",
                         "p": p_txt(r["p_two_sided"])})
        rep.add(key, f"T{key[1:3]}. ISIC 2020 paired bootstrap, hybrid − {a_label} (test, 1,000 resamples)",
                pd.DataFrame(rows), [rel(CMP_DIR / f"{stem}.json")],
                ["Each model at its own cutoffs fixed on val; not a comparison at equal sensitivity."])


def t4_xai_localisation(rep: Report) -> None:
    rows, src, refs = [], [], None
    for run, label, _ in XAI_RUNS:
        path, rpath = RUNS_DIR / run / "xai_val" / "summary.json", RUNS_DIR / run / "xai_val_random" / "summary.json"
        s, r = read_json(path), read_json(rpath)
        if s is None:
            rows.append({"Model": label, "Map": "not run"})
            continue
        src += [rel(path)] + ([rel(rpath)] if r else [])
        for key, v in s["maps"].items():
            name, target = key.split("@")
            if name.startswith("ref_"):
                refs = refs or s["maps"]
                continue
            if target == "true":
                continue
            a = v["all"]
            ra = r["maps"].get(key, {}).get("all", {}) if r else {}
            rows.append({"Model": label, "Map": MAP_LABELS.get(name, name), "IoU": f(a["iou"], 3),
                         "Dice": f(a["dice"], 3), "Box IoU": f(a["bbox_iou"], 3), "Pointing": f(a["pointing"], 3),
                         "Energy in mask": f(a["energy_in_mask"], 3), "Random: IoU": f(ra.get("iou"), 3),
                         "Random: pointing": f(ra.get("pointing"), 3), "Random: energy": f(ra.get("energy_in_mask"), 3)})
    for key, name in [("ref_centre@none", "reference: centred Gaussian"), ("ref_uniform@none", "reference: uniform")]:
        if refs and key in refs:
            a = refs[key]["all"]
            rows.append({"Model": "—", "Map": name, "IoU": f(a["iou"], 3), "Dice": f(a["dice"], 3),
                         "Box IoU": f(a["bbox_iou"], 3), "Pointing": f(a["pointing"], 3),
                         "Energy in mask": f(a["energy_in_mask"], 3)})
    rep.add("t4_ham10000_xai_val", "T4. HAM10000 val XAI localisation (n = 1,503; Grad-CAM for the predicted class)",
            pd.DataFrame(rows), src,
            ["Binarised at 15% of max (Grad-CAM §4.1); random = same architecture with random weights."])


def comparison_rows(cmp: dict, map_key: str) -> list[dict]:
    res, primary, bound = cmp["results"][map_key], cmp["primary"], holm_bound(cmp)
    rows = []
    for metric, r in res.items():
        rows.append({"Endpoint": metric, "Primary": "yes" if metric in primary else "",
                     "Better": r["better"], "A": f(r["a"]), "B": f(r["b"]),
                     "B − A [95% CI]": f"{mark(r, 4)} {ci_txt(r['diff_ci'])}",
                     "p": p_txt(r["p_two_sided"]), "p Holm": p_txt(r["p_holm"], bound) if "p_holm" in r else ""})
    return rows


def t5_m4(rep: Report) -> None:
    for split in ("val", "test"):
        path = CMP_DIR / f"{M4_STEM.format(split=split)}.json"
        cmp = read_json(path)
        if cmp is None:
            continue
        rows = []
        for map_key in cmp["results"]:
            for row in comparison_rows(cmp, map_key):
                rows.append({"Hybrid map (B)": MAP_LABELS[map_key]} | row)
            rows.append({"Hybrid map (B)": MAP_LABELS[map_key], "Endpoint": "**frozen decision rule**",
                         "B − A [95% CI]": f"**{decision_rule(cmp['results'][map_key], cmp['primary'])}**"})
        kind = "confirmatory" if split == "test" else "not confirmatory: these data informed post-val changes"
        rep.add(f"t5_m4_trust_{split}",
                f"T5 ({split}). M4 explanation trust: hybrid map (B) vs ConvNeXt-T Grad-CAM (A), {split} "
                f"n = {cmp['n']:,} ({kind})", pd.DataFrame(rows), [rel(path)],
                [f"Holm over {len(cmp['primary'])} primary endpoints × {len(cmp['results'])} maps; "
                 f"Holm bound for p = 0: < {holm_bound(cmp):.3f}."])


def compact_rows(specs: list[tuple[str, str, bool]], fmt: dict, label_fmt: dict) -> tuple[list[dict], list[str]]:
    """One row per comparison x map: primary endpoints as 'val / test' with ▲/▼ marks, and the verdicts."""
    rows, src = [], []
    for label, stem, ruled in specs:
        cmps = {}
        for split in ("val", "test"):
            path = CMP_DIR / f"{stem.format(split=split, **fmt)}.json"
            cmps[split] = read_json(path)
            if cmps[split] is not None:
                src.append(rel(path))
        first = cmps["val"] or cmps["test"]
        if first is None:
            rows.append({"Comparison": label.format(**label_fmt), "Map (B)": "not run"})
            continue
        for map_key in first["results"]:
            row = {"Comparison": label.format(**label_fmt), "Map (B)": MAP_LABELS[map_key],
                   "n val / test": " / ".join(str(cmps[s]["n"]) if cmps[s] else "—" for s in ("val", "test"))}
            for metric in first["primary"]:
                row[metric] = " / ".join(mark(cmps[s]["results"][map_key].get(metric), 3) if cmps[s] else "—"
                                         for s in ("val", "test"))
            row["Rule val / test"] = " / ".join(
                (decision_rule(cmps[s]["results"][map_key], cmps[s]["primary"]) if ruled else "descriptive")
                if cmps[s] else "—" for s in ("val", "test"))
            rows.append(row)
    return rows, src


def t6_part_b(rep: Report) -> None:
    rows, src = [], []
    for m, name in STEP4_METHODS:
        r, s = compact_rows(STEP4, {"m": m}, {"M": name})
        rows += [{"Method": name} | x for x in r]
        src += s
    rep.add("t6a_partb_step4", f"T6a. Part B step 4 ({EXPLORATORY}): SmoothGrad-CAM and Score-CAM, B − A val / test",
            pd.DataFrame(rows), src,
            [f"{EXPLORATORY}: settings and rule frozen on val before the single test run; the HAM10000 test set "
             "had already been used by M4.",
             "SmoothGrad-CAM on all 1,503 images per split; Score-CAM on a fixed stratified 150-image subset.",
             "Score-CAM on ConvNeXt-T: 27 / 150 (val) and 24 / 150 (test) maps are all zero, because its hooked "
             "layer is signed and the Score-CAM weights are all positive (docs/report_notes.md, step 4). Score-CAM "
             "comparisons (a) and (c) therefore mostly measure this failure; (a) fused meeting the rule on test is "
             "not evidence that the hybrid map is more trustworthy."])

    sel_rows, sel_src = [], []
    for stage in ("lambda", "consistency"):
        path = CMP_DIR / f"ham10000_mask_guided_{stage}.json"
        sel = read_json(path)
        if sel is None:
            continue
        sel_src.append(rel(path))
        if stage == "lambda":
            s = sel["source"]
            sel_rows.append({"Stage": "source", "Run": s["run"], "Val macro-F1": f(s["val_macro_f1"]),
                             "Eligible": "—", "Screen insertion_vs_random": f(s["insertion_vs_random"], 3),
                             "Screen stab_spearman_mean": f(s["stab_spearman_mean"], 3), "Screen IoU": f(s["iou"], 3),
                             "Chosen": ""})
        for c in sel["candidates"]:
            if any(r["Run"] == c["run"] for r in sel_rows):
                continue
            sel_rows.append({"Stage": stage, "Run": c["run"], "Val macro-F1": f(c["val_macro_f1"]),
                             "Eligible": "yes" if c["eligible"] else "no",
                             "Screen insertion_vs_random": f(c["insertion_vs_random"], 3),
                             "Screen stab_spearman_mean": f(c["stab_spearman_mean"], 3), "Screen IoU": f(c["iou"], 3),
                             "Chosen": ""})
        for r in sel_rows:
            if r["Run"] == sel["chosen"] and stage == "consistency":
                r["Chosen"] = "final"
    if sel_rows:
        rule = read_json(CMP_DIR / "ham10000_mask_guided_consistency.json")
        rep.add("t6b_partb_step5_selection",
                f"T6b. Part B step 5 ({EXPLORATORY}): mask-guided candidates, selection on val",
                pd.DataFrame(sel_rows), sel_src,
                [f"Rule: {rule['rule'] if rule else '—'}; screen = fixed 300-image val subset, fused map.",
                 "Selection bias: the screening images are part of the val set used in T6c, so val comparisons of "
                 "the chosen run are optimistic."])
    rows, src = compact_rows(STEP5, {}, {})
    rep.add("t6c_partb_step5", f"T6c. Part B step 5 ({EXPLORATORY}): mask-guided hybrid, B − A val / test",
            pd.DataFrame(rows), src,
            [f"{EXPLORATORY}. Classification of the mask-guided run vs the source hybrid: T2 (last row)."])


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--out", default="outputs/results")
    args = p.parse_args()
    out = Path(args.out)
    out = out if out.is_absolute() else PROJECT_DIR / out
    out.mkdir(parents=True, exist_ok=True)
    rep = Report(out)
    for table in (t1_ham_classification, t2_ham_paired, t3_isic, t4_xai_localisation, t5_m4, t6_part_b):
        table(rep)
    print(rep.write())


if __name__ == "__main__":
    main()
