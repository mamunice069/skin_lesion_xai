"""Results tables for the report, generated only from files the runs wrote (no number is typed in here).

Usage: python scripts/compare_results.py [--out outputs/results]

Reads outputs/runs/<run>/{train_summary.json, eval/metrics.json, xai_val/summary.json, xai_val_random/summary.json}
and outputs/comparisons/*.json; writes <out>/tables.md (every table, each followed by its source files) and one
CSV per table. The run lists and comparison files are defined in skin_lesion_xai/eval/results.py; a listed run whose
files are missing is shown as "not run". Verdicts are computed by decision_rule() from the Holm
p-values in the comparison files, not copied from the notes.
  T1 HAM10000 classification          T2 HAM10000 paired classification tests (+ Holm over the two pre-specified)
  T3 ISIC 2020 test + paired test      T4 HAM10000 val XAI localisation (M3b)
  T5 M4 explanation trust (confirmatory, val and test)
  T6 Part B (EXPLORATORY): step 4 other CAM methods, step 5 mask-guided fine-tuning
"""
from __future__ import annotations

import argparse
from pathlib import Path

import pandas as pd

from skin_lesion_xai.config import PROJECT_DIR
from skin_lesion_xai.eval.metrics import holm
from skin_lesion_xai.eval.results import (
    CMP_DIR, EXPLORATORY, HAM_PAIRED, HAM_RUNS, ISIC_PAIRED, ISIC_PAIRED_LOCAL, ISIC_RUNS, M4_STEM, MAP_LABELS,
    MIN_P, NOT_WORSE_MARGIN, RUNS_DIR, STEP4, STEP4_METHODS, STEP5, XAI_RUNS, decision_rule, direction, holm_bound,
    is_nan, read_json, rel,
)


# ----------------------------------------------------------------------------------------------- formatting
def f(v, d: int = 4) -> str:
    return "—" if is_nan(v) else f"{v:.{d}f}"


def signed(v, d: int = 4) -> str:
    return "—" if is_nan(v) else f"{v:+.{d}f}".replace("-", "−")


def ci_txt(ci: dict | None, d: int = 4) -> str:
    if not ci or is_nan(ci.get("low")):
        return ""
    return f"[{f(ci['low'], d)}, {f(ci['high'], d)}]".replace("-", "−")


def p_txt(p, bound: float = MIN_P) -> str:
    """A p of exactly 0 means no resample crossed zero: report the resolution bound instead."""
    if is_nan(p):
        return "—"
    return f"< {bound:.3f}" if p == 0 else f"{p:.3f}"


def mark(r: dict | None, d: int) -> str:
    if r is None:
        return "—"
    return {1: "▲", -1: "▼", 0: ""}[direction(r)] + signed(r["diff"], d)


def md_table(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        lines.append("| " + " | ".join("" if is_nan(v) else str(v) for v in row) + " |")
    return "\n".join(lines)


class Report:
    def __init__(self, out_dir: Path):
        self.out_dir, self.parts = out_dir, []

    def add(self, key: str, title: str, df: pd.DataFrame, sources: list[str], notes: list[str] = ()) -> None:
        df.to_csv(self.out_dir / f"{key}.csv", index=False)
        text = [f"## {title}", "", md_table(df), ""]
        text += [f"- {n}" for n in notes]
        text += ["", "Sources: " + ", ".join(f"`{s}`" for s in sorted(set(sources))), ""]
        self.parts.append("\n".join(text))

    def write(self) -> Path:
        head = ["# Results tables", "",
                "Generated by `scripts/compare_results.py` from the run outputs; do not edit by hand. "
                "Part B rows are marked EXPLORATORY: the HAM10000 test set had already been used once by M4.",
                "▲ / ▼ = significantly better / worse for B (Holm p < 0.05 within the comparison); "
                "p = 0 in a file means no resample crossed zero, shown as < 0.002 (raw) or < m × 0.002 (Holm, "
                "m = number of Holm-corrected tests in that comparison).", ""]
        path = self.out_dir / "tables.md"
        path.write_text("\n".join(head + self.parts), encoding="utf-8")
        return path


