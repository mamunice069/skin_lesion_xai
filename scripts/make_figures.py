def figure_images(split: str = "test"):
    """Positions, images (RGB), masks, image ids and labels of the explain.py figure images."""
    from skin_lesion_xai.data.datasets import build_dataset
    from skin_lesion_xai.data.transforms import build_eval_transform
    from skin_lesion_xai.xai.visualize import denormalize, figure_indices

    snap = json.loads((RUNS_DIR / "ham10000_hybrid" / "config.json").read_text())
    data_cfg, xcfg = DataConfig(**snap["data"]), XaiConfig.from_yaml(PROJECT_DIR / "configs/xai/default.yaml")
    ds = build_dataset(data_cfg, split, build_eval_transform(data_cfg.image_size), return_mask=True)
    picks = figure_indices(ds.labels, xcfg.figures_per_class, xcfg.figure_seed)
    items = [ds[i] for i in picks]
    return (picks, [denormalize(it["image"]) for it in items], [it["mask"].numpy().astype(bool) for it in items],
            [it["image_id"] for it in items], [int(it["label"]) for it in items], data_cfg)


def nth_per_class(labels: list[int], n: int) -> list[int]:
    """Positions (in the figure-image list) of the n-th image of each class (0 = first)."""
    count, keep = {}, []
    for k, c in enumerate(labels):
        if count.get(c, 0) == n:
            keep.append(k)
        count[c] = count.get(c, 0) + 1
    return keep


def row_label(ax, text: str) -> None:
    ax.text(-0.06, 0.5, text, transform=ax.transAxes, rotation=90, ha="right", va="center", fontsize=6)


def image_grid(n_rows: int, n_cols: int):
    """Page-width grid of square panels, one column per image (IEEE two-column figure*)."""
    side = (PAGE - 0.25) / n_cols
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(PAGE, side * 1.2 * n_rows + 0.15), squeeze=False)
    return fig, axes


