def f5_m4(figs: Figures) -> None:
    path = CMP_DIR / f"{M4_STEM.format(split='test')}.json"
    cmp = read_json(path)
    conv, hyb = (read_json(RUNS_DIR / r / "trust_test" / "summary.json") for r in ("ham10000_convnext_t", "ham10000_hybrid"))
    if cmp is None or conv is None or hyb is None:
        return skip("F5", "M4 test comparison or trust_test summaries missing")
    fig = plt.figure(figsize=(PAGE, 5.0))
    grid = fig.add_gridspec(3, 6, height_ratios=[1.2, 0.22, 1])
    lines = [(conv, "gradcam", "ConvNeXt-T Grad-CAM", "#1f77b4", "-"),
             (hyb, "gradcam_local", f"Hybrid, {SHORT_MAP['gradcam_local']}", "#d62728", "-"),
             (hyb, "gradcam_fused", "Hybrid, fused", "#ff7f0e", "-"),
             (conv, "ref_random", "random map (ConvNeXt-T)", "#1f77b4", ":"),
             (hyb, "ref_random", "random map (hybrid)", "#d62728", ":")]
    handles = []
    for k, mode in enumerate(("deletion", "insertion")):
        ax = fig.add_subplot(grid[0, 3 * k:3 * k + 3])
        for summ, name, label, colour, ls in lines:
            curve = np.asarray(summ["mean_curves"][f"{name}@{mode}"])
            (line,) = ax.plot(np.linspace(0, 1, len(curve)), curve, color=colour, ls=ls, lw=1.2)
            if k == 0:
                aucs = "/".join(f"{summ['means'][name][f'{m}_auc']:.3f}" for m in ("deletion", "insertion"))
                handles.append((line, f"{label} ({aucs})"))
        ax.set(xlabel=f"share of pixels {'removed' if mode == 'deletion' else 'restored'}",
               ylabel="probability of the predicted class",
               title=f"({'ab'[k]}) {mode.capitalize()} ({'lower' if mode == 'deletion' else 'higher'} area is better)")
        ax.grid(alpha=0.3)
    legend_ax = fig.add_subplot(grid[1, :])
    legend_ax.axis("off")
    legend_ax.legend(*zip(*handles), loc="center", ncol=3, frameon=False, fontsize=6,
                     title="mean AUC deletion / insertion in brackets", title_fontsize=6)
    maps = list(cmp["results"])
    for k, metric in enumerate(cmp["primary"]):
        ax = fig.add_subplot(grid[2, k])
        for y, m in enumerate(maps):
            r = cmp["results"][m][metric]
            ax.errorbar(r["diff"], y, xerr=[[r["diff"] - r["diff_ci"]["low"]], [r["diff_ci"]["high"] - r["diff"]]],
                        fmt="o", ms=4, capsize=2, color=DIR_COLOURS[direction(r)])
        ax.axvline(0, color="k", lw=0.6)
        ax.set_ylim(-0.6, len(maps) - 0.4)
        ax.set_yticks(range(len(maps)))
        ax.set_yticklabels([SHORT_MAP[m] for m in maps] if k == 0 else [])
        if k == 0:
            panel_letter(ax, "c", x=-0.9, y=1.32)
        better = cmp["results"][maps[0]][metric]["better"]
        ax.set_title(f"{PRIMARY_LABELS.get(metric, metric)}\n({better} is better)", fontsize=6)
        ax.tick_params(axis="x", labelsize=6)
        ax.xaxis.set_major_locator(MaxNLocator(nbins=3, symmetric=True))
    verdicts = ", ".join(f"{SHORT_MAP[m]}: {decision_rule(cmp['results'][m], cmp['primary'])}"
                         for m in maps)
    fig.suptitle(f"M4 explanation trust, HAM10000 test (n = {cmp['n']:,}, confirmatory). Frozen rule — {verdicts}", fontsize=7.5)
    fig.tight_layout()
    figs.save(fig, "F5_m4_trust_test",
              "Top: mean deletion and insertion curves (blur fill; mean AUC in brackets) for ConvNeXt-T Grad-CAM, "
              "the hybrid's two Grad-CAM maps and each model's random-map reference. Bottom: paired differences, "
              "hybrid map minus ConvNeXt-T, on the six primary endpoints with 95% CI; green / red = significantly "
              "better / worse after Holm over 12 tests, grey = not significant.",
              [rel(path), rel(RUNS_DIR / "ham10000_convnext_t" / "trust_test" / "summary.json"),
               rel(RUNS_DIR / "ham10000_hybrid" / "trust_test" / "summary.json")])


