class Figures:
    def __init__(self, out_dir: Path, formats: tuple[str, ...] = ("png", "pdf")):
        self.out_dir, self.captions, self.formats = out_dir, [], formats

    def save(self, fig, name: str, caption: str, sources: list[str]) -> None:
        for ext, dpi in (("png", 200), ("pdf", None)):
            if ext not in self.formats:
                continue
            fig.savefig(self.out_dir / f"{name}.{ext}", dpi=dpi, bbox_inches="tight")
        plt.close(fig)
        src = ", ".join(f"`{s}`" for s in sorted(set(sources)))
        self.captions.append(f"## {name}\n\n{caption}\n\nSources: {src}\n")
        print("wrote", self.out_dir / name, "+".join(self.formats))

    def write_captions(self, keep_others: bool = False) -> None:
        """keep_others: keep the captions of figures not redrawn this time (a partial run with --only)."""
        head = "# Figure captions\n\nGenerated by `scripts/make_figures.py`; do not edit by hand.\n\n"
        path = self.out_dir / "captions.md"
        sections = {c.split("\n", 1)[0]: c for c in self.captions}
        if keep_others and path.exists():
            old = path.read_text(encoding="utf-8").split("\n## ")[1:]
            sections = {f"## {s.split(chr(10), 1)[0]}": f"## {s.rstrip()}\n" for s in old} | sections
        path.write_text(head + "\n".join(sections[k] for k in sorted(sections)), encoding="utf-8")


def skip(name: str, why: str) -> None:
    print(f"skipped {name}: {why}")


def panel_letter(ax, letter: str, x: float = -0.02, y: float = 1.02) -> None:
    """Panel label (a), (b), ... as in the related papers' multi-panel figures."""
    ax.text(x, y, f"({letter})", transform=ax.transAxes, fontsize=7.5, fontweight="bold", ha="right", va="bottom")


def role_group(role: str) -> str:
    if role.startswith(EXPLORATORY):
        return "exploratory"
    for key in ("proposed", "fusion", "hair"):
        if key in role:
            return key
    return "branch" if ("branch alone" in role or "norm fix" in role) and not role.startswith("baseline") \
        else "baseline"


def overlay(ax, rgb: np.ndarray, heatmap: np.ndarray | None, mask: np.ndarray, title: str) -> None:
    ax.imshow(rgb)
    if heatmap is not None:
        ax.imshow(heatmap, cmap="jet", alpha=0.45, vmin=0, vmax=1)
    if mask.any():
        ax.contour(mask.astype(float), levels=[0.5], colors="white", linewidths=0.8)
    ax.set_title(title, fontsize=5.5, pad=2)
    ax.axis("off")


