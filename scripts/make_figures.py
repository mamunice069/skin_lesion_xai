def f1_classification(figs: Figures) -> None:
    rows, src = [], []
    for run, label, role in HAM_RUNS:
        s, m = read_json(RUNS_DIR / run / "train_summary.json"), read_json(RUNS_DIR / run / "eval" / "metrics.json")
        if s is None or m is None:
            continue
        src += [rel(RUNS_DIR / run / "train_summary.json"), rel(RUNS_DIR / run / "eval" / "metrics.json")]
        rows.append((label, role_group(role), m["test"]["macro_f1"], m["test_ci95"]["macro_f1"], s["best_val_score"]))
    if not rows:
        return skip("F1", "no evaluated HAM10000 run")
    fig, ax = plt.subplots(figsize=(COL, 0.2 * len(rows) + 1.0))
    for y, (label, group, test, ci, val) in enumerate(reversed(rows)):
        c = ROLE_COLOURS[group]
        ax.errorbar(test, y, xerr=[[test - ci["low"]], [ci["high"] - test]], fmt="o", color=c, ms=4, capsize=2)
        ax.plot(val, y, marker="o", mfc="none", mec=c, ms=5, ls="none")
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels([r[0] + (f" ({EXPLORATORY})" if r[1] == "exploratory" else "") for r in reversed(rows)])
    ax.set_xlabel("Macro-F1")
    ax.grid(axis="x", alpha=0.3)
    handles = [plt.Line2D([], [], color=ROLE_COLOURS[g], marker="o", ls="none", label=g)
               for g in ROLE_COLOURS if any(r[1] == g for r in rows)]
    handles += [plt.Line2D([], [], color="k", marker="o", ls="none", ms=4, label="test [95% CI]"),
                plt.Line2D([], [], color="k", marker="o", mfc="none", ls="none", label="val (best epoch)")]
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.35, -0.13), frameon=False, ncol=3)
    figs.save(fig, "F1_ham10000_classification",
              "Test macro-F1 with its 95% bootstrap CI (filled) and best-epoch val macro-F1 (hollow) for every "
              "evaluated HAM10000 run, coloured by role. Hair-removed runs are evaluated on their own DullRazor "
              f"test images. The mask-guided run is Part B ({EXPLORATORY}).", src)


def f2_paired(figs: Figures) -> None:
    loaded = [(stem, label, fam, read_json(CMP_DIR / f"{stem}.json")) for stem, label, fam in HAM_PAIRED]
    loaded = [x for x in loaded if x[3] is not None]
    isic = read_json(CMP_DIR / f"{ISIC_PAIRED}.json")
    if not loaded and isic is None:
        return skip("F2", "no paired comparison file")
    adj = holm({stem: c["metrics"]["macro_f1"]["p_two_sided"] for stem, _, fam, c in loaded if fam})
    fig, axes = plt.subplots(2, 1, figsize=(COL, 3.0), gridspec_kw={"height_ratios": [3, 2]})

    def interval(ax, r, y, colour):
        ax.errorbar(r["diff"], y, xerr=[[r["diff"] - r["diff_ci"]["low"]], [r["diff_ci"]["high"] - r["diff"]]],
                    fmt="o", color=colour, ms=3.5, capsize=2)

    ax, labels = axes[0], []
    for y, (stem, label, fam, c) in enumerate(reversed(loaded)):
        r = c["metrics"]["macro_f1"]
        colour = ROLE_COLOURS["exploratory"] if fam is None else "k"
        interval(ax, r, y, colour)
        p = f"p {r['p_two_sided']:.3f}" + (f", Holm {adj[stem]:.3f}" if stem in adj else "")
        labels.append(f"{label.replace(f' ({EXPLORATORY})', '*')}\n{p}")
        if fam is None:
            ax.plot([NOT_WORSE_MARGIN] * 2, [y - 0.35, y + 0.35], ls="--", color=colour, lw=1)
    ax.axvline(0, color="k", lw=0.6)
    ax.set_yticks(range(len(loaded)))
    ax.set_yticklabels(labels, fontsize=5.5)
    ax.set_xlabel("HAM10000 test: macro-F1, B − A [95% CI]")
    ax.set_ylim(-0.6, len(loaded) - 0.4)
    ax = axes[1]
    if isic is not None:
        rows = [("average_precision", "AP"), ("auc", "AUC")]
        for y, (metric, _) in enumerate(rows):
            interval(ax, isic["metrics"][metric], y, "k")
        ax.axvline(0, color="k", lw=0.6)
        ax.set_yticks(range(len(rows)))
        ax.set_yticklabels([f"{name}\np {isic['metrics'][m]['p_two_sided']:.3f}" for m, name in rows], fontsize=5.5)
        ax.set_xlabel(f"ISIC 2020 test (n = {isic['n']:,}): hybrid − ConvNeXt-T [95% CI]")
        ax.set_ylim(-0.6, len(rows) - 0.4)
    for a, letter in zip(axes, "ab"):
        a.grid(axis="x", alpha=0.3)
        panel_letter(a, letter)
    fig.tight_layout(h_pad=0.6)
    figs.save(fig, "F2_paired_classification",
              "Paired bootstrap differences (1,000 shared resamples). Top: HAM10000 macro-F1, Holm over the two "
              "pre-specified comparisons; the mask-guided row (*, grey) is Part B "
              f"({EXPLORATORY}), with its pre-set −0.01 \"not worse\" margin dashed. Bottom: ISIC 2020 "
              "hybrid minus ConvNeXt-T.", [rel(CMP_DIR / f"{s}.json") for s, _, _, _ in loaded]
              + ([rel(CMP_DIR / f"{ISIC_PAIRED}.json")] if isic else []))


