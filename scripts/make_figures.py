def f7_part_b(figs: Figures) -> None:
    specs = [(name, label.format(M=name), stem.format(split="{split}", m=m), ruled)
             for m, name in STEP4_METHODS for label, stem, ruled in STEP4]
    specs += [("Mask-guided", label, stem, ruled) for label, stem, ruled in STEP5]
    rows, values, texts, verdicts, src, primary = [], [], [], [], [], None
    for group, label, stem, ruled in specs:
        cmps = {}
        for split in ("val", "test"):
            path = CMP_DIR / f"{stem.format(split=split)}.json"
            cmps[split] = read_json(path)
            src += [rel(path)] if cmps[split] else []
        first = cmps["val"] or cmps["test"]
        if first is None:
            continue
        primary = primary or first["primary"]
        letter = label[:3]
        for m in first["results"]:
            rows.append(f"{F7_GROUP[group]} {letter} {F7_CMP[letter]}" + (f", {F7_MAP[m]}" if F7_MAP[m] else ""))
            v, t = [], []
            for metric in primary:
                for split in ("val", "test"):
                    r = cmps[split]["results"][m].get(metric) if cmps[split] else None
                    v.append(np.nan if r is None else direction(r))
                    t.append("" if r is None else f"{r['diff']:+.3f}")
            values.append(v)
            texts.append(t)
            verdicts.append(" / ".join(F7_RULE[(decision_rule(cmps[s]["results"][m], cmps[s]["primary"]) if ruled
                                                else "descriptive")] if cmps[s] else "—" for s in ("val", "test")))
    if not rows:
        return skip("F7", "no Part B comparison file")
    data = np.array(values, dtype=float)
    fig, ax = plt.subplots(figsize=(PAGE, 0.2 * len(rows) + 0.9))
    ax.imshow(np.ma.masked_invalid(data + 1), cmap=ListedColormap([DIR_COLOURS[-1], "#e6e6e6", DIR_COLOURS[1]]),
              vmin=0, vmax=2, aspect="auto")
    for i, row in enumerate(texts):
        for j, t in enumerate(row):
            ax.text(j, i, t, ha="center", va="center", fontsize=5,
                    color="white" if data[i, j] in (-1, 1) else "black")
        ax.text(len(row) - 0.35, i, verdicts[i], ha="left", va="center", fontsize=5.5)
    for i in range(1, len(rows)):  # thin rule between method groups
        if rows[i].split()[0] != rows[i - 1].split()[0]:
            ax.axhline(i - 0.5, color="k", lw=0.8)
    ax.set_yticks(range(len(rows)))
    ax.set_yticklabels(rows, fontsize=5.5)
    ax.set_xticks(range(data.shape[1]))
    ax.set_xticklabels(["val", "test"] * len(primary), fontsize=5)
    ax.tick_params(axis="x", length=0, pad=1)
    for k, metric in enumerate(primary):
        ax.text(2 * k + 0.5, -0.75, F7_ENDPOINT.get(metric, metric), ha="center", va="bottom", fontsize=5.5)
        if k:
            ax.axvline(2 * k - 0.5, color="white", lw=2)
    ax.text(data.shape[1] - 0.35, -0.75, "rule\nval / test", ha="left", va="bottom", fontsize=5.5)
    ax.set_title(f"Part B ({EXPLORATORY}): B − A; green / red = significantly better / worse for B (Holm p < 0.05)",
                 fontsize=6.5, pad=12)
    fig.tight_layout()
    figs.save(fig, "F7_part_b_summary",
              f"{EXPLORATORY}: settings and decision rules frozen on val before one test run; the HAM10000 test set "
              "had already been used by M4. SG = SmoothGrad-CAM, SC = Score-CAM, Mask = mask-guided fine-tuning. "
              "(a) hybrid vs ConvNeXt-T with the same method, (b) the method vs the hybrid's own Grad-CAM, (c) the "
              "method vs ConvNeXt-T's own Grad-CAM (descriptive), (d) mask-guided vs source hybrid, (e) mask-guided "
              "vs ConvNeXt-T Grad-CAM. Rule: met / no (not met) on val / test. Score-CAM uses a fixed 150-image "
              "subset; on ConvNeXt-T 27 / 150 (val) and 24 / 150 (test) of its maps are all zero (signed layer, "
              "positive weights), so Score-CAM (a) and (c) mostly measure that failure.", src)


def f8_training(figs: Figures) -> None:
    runs = [("ham10000_convnext_t", "ConvNeXt-T", "#1f77b4"), ("ham10000_hybrid", "Hybrid, cross-attention", "#d62728"),
            ("ham10000_hybrid_concat", "Hybrid, concat", "#2ca02c")]
    runs = [r for r in runs if (RUNS_DIR / r[0] / "history.csv").exists()]
    if not runs:
        return skip("F8", "no history.csv")
    fig, (f1_ax, loss_ax) = plt.subplots(1, 2, figsize=(PAGE, 2.4))
    src = []
    for run, label, colour in runs:
        h = pd.read_csv(RUNS_DIR / run / "history.csv")
        s = read_json(RUNS_DIR / run / "train_summary.json")
        src += [rel(RUNS_DIR / run / "history.csv")] + ([rel(RUNS_DIR / run / "train_summary.json")] if s else [])
        f1_ax.plot(h["epoch"], h["val_macro_f1"], color=colour, lw=1.2, label=label)
        loss_ax.plot(h["epoch"], h["train_loss"], color=colour, lw=1.2, label=f"{label}, train")
        loss_ax.plot(h["epoch"], h["val_loss"], color=colour, lw=1.2, ls="--", label=f"{label}, val")
        if s:
            best = h.loc[h["epoch"] == s["best_epoch"], "val_macro_f1"]
            f1_ax.plot(s["best_epoch"], best, "*", color=colour, ms=9)
    f1_ax.set(xlabel="epoch", ylabel="val macro-F1 (EMA weights)", title="(a) Validation macro-F1 (★ = checkpoint)")
    loss_ax.set(xlabel="epoch", ylabel="loss (CE, label smoothing 0.1)", title="(b) Train and val loss")
    for ax in (f1_ax, loss_ax):
        ax.grid(alpha=0.3)
        ax.legend(frameon=False, fontsize=6)
    fig.tight_layout()
    figs.save(fig, "F8_training_curves",
              "HAM10000 training history; training stopped after 7 epochs without a val macro-F1 gain, and the "
              "starred epoch is the checkpoint used everywhere.", src)


