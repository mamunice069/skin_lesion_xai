def f3_isic(figs: Figures) -> None:
    runs = [(run, label) for run, label in ISIC_RUNS if (RUNS_DIR / run / "eval" / "predictions.csv").exists()]
    if not runs:
        return skip("F3", "no ISIC 2020 test predictions")
    fig, (roc_ax, pr_ax) = plt.subplots(1, 2, figsize=(PAGE, 2.7))
    src = []
    for i, (run, label) in enumerate(runs):
        pred = pd.read_csv(RUNS_DIR / run / "eval" / "predictions.csv")
        m = read_json(RUNS_DIR / run / "eval" / "metrics.json")
        src += [rel(RUNS_DIR / run / "eval" / "predictions.csv"), rel(RUNS_DIR / run / "eval" / "metrics.json")]
        y, p, c = pred["label"].to_numpy(), pred["p_melanoma"].to_numpy(), f"C{i}"
        fpr, tpr, _ = roc_curve(y, p)
        prec, rec, _ = precision_recall_curve(y, p)
        roc_ax.plot(fpr, tpr, color=c, lw=1, label=f"{label} (AUC {m['test']['auc']:.3f})")
        pr_ax.plot(rec, prec, color=c, lw=1, label=f"{label} (AP {m['test']['average_precision']:.3f})")
        for key, marker in (("youden", "o"), ("sensitivity_0.80", "s")):
            t = m["test_at_val_thresholds"][key]["threshold"]
            hit = p >= t  # as compare_paired.py: ties count as melanoma
            sens, spec = hit[y == 1].mean(), (~hit[y == 0]).mean()
            prec_t = hit[y == 1].sum() / max(hit.sum(), 1)
            roc_ax.plot(1 - spec, sens, marker=marker, color=c, mfc="none", ms=6)
            pr_ax.plot(sens, prec_t, marker=marker, color=c, mfc="none", ms=6)
    roc_ax.plot([0, 1], [0, 1], color="k", lw=0.5, ls=":")
    roc_ax.set(xlabel="1 − specificity", ylabel="sensitivity", title="(a) ROC, ISIC 2020 test")
    pr_ax.set(xlabel="recall (sensitivity)", ylabel="precision", title="(b) Precision–recall, ISIC 2020 test")
    for ax in (roc_ax, pr_ax):
        ax.legend(loc="lower right" if ax is roc_ax else "upper right", frameon=False)
        ax.grid(alpha=0.3)
    roc_ax.plot([], [], "ko", mfc="none", label="Youden cutoff (val)")
    roc_ax.plot([], [], "ks", mfc="none", label="sens ≥ 0.80 cutoff (val)")
    roc_ax.legend(loc="lower right", frameon=False)
    fig.tight_layout()
    figs.save(fig, "F3_isic2020_roc_pr",
              "ROC and precision–recall curves on the ISIC 2020 test set; markers are each model's own cutoffs "
              "fixed on val (circle Youden, square sensitivity ≥ 0.80), computed from predictions.csv with ties "
              "counted as melanoma (as compare_paired.py). Runs without test predictions are not shown.", src)


def f4_localisation(figs: Figures) -> None:
    rows, src, refs = [], [], None
    for run, label, _ in XAI_RUNS:
        s = read_json(RUNS_DIR / run / "xai_val" / "summary.json")
        r = read_json(RUNS_DIR / run / "xai_val_random" / "summary.json")
        if s is None:
            continue
        src += [rel(RUNS_DIR / run / "xai_val" / "summary.json")]
        src += [rel(RUNS_DIR / run / "xai_val_random" / "summary.json")] if r else []
        for key, v in s["maps"].items():
            name, target = key.split("@")
            if name.startswith("ref_"):
                refs = refs or s["maps"]
                continue
            if target == "true":
                continue
            ra = r["maps"].get(key, {}).get("all", {}) if r else {}
            rows.append((f"{label} — {MAP_LABELS.get(name, name)}", v["all"], ra))
    if not rows:
        return skip("F4", "no xai_val summary")
    fig, axes = plt.subplots(1, 2, figsize=(PAGE, 0.17 * len(rows) + 0.8), sharey=True)
    for ax, metric, title in ((axes[0], "iou", "IoU"), (axes[1], "energy_in_mask", "Energy in mask")):
        for y, (_, a, ra) in enumerate(reversed(rows)):
            ax.plot(a[metric], y, "o", color="k", ms=4)
            if ra.get(metric) is not None:
                ax.plot(ra[metric], y, "o", mfc="none", mec="#c0392b", ms=4)
        if refs:
            ax.axvline(refs["ref_centre@none"]["all"][metric], color="#1f77b4", ls="--", lw=1, label="centred Gaussian")
            ax.axvline(refs["ref_uniform@none"]["all"][metric], color="#1f77b4", ls=":", lw=1, label="uniform map")
        ax.set_xlabel(title)
        ax.grid(axis="x", alpha=0.3)
    axes[0].set_yticks(range(len(rows)))
    axes[0].set_yticklabels([r[0] for r in reversed(rows)])
    axes[1].plot([], [], "ko", ms=4, label="trained")
    axes[1].plot([], [], "o", mfc="none", mec="#c0392b", label="random weights")
    axes[1].legend(loc="lower right", frameon=False)
    fig.tight_layout()
    figs.save(fig, "F4_ham10000_localisation_val",
              "IoU (map binarised at 15% of its max) and share of map energy inside the lesion for every map, "
              "trained (filled) and with random weights (hollow), against two input-independent reference maps.", src)


